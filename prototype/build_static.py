"""Build docs/index.html: the Streamlit app running in the browser via stlite (Pyodide), no server needed.

Run from anywhere:  python prototype/build_static.py
Re-run after changing any app, scorer, data or write-up file so the HTML stays in sync.
"""
import json
import pathlib

REPO = pathlib.Path(__file__).resolve().parents[1]
STLITE = "https://cdn.jsdelivr.net/npm/@stlite/browser@1.9.2/build"   # pinned version

FILES = [
    "prototype/app.py", "prototype/config.py", "prototype/scorer.py",
    "prototype/data/gold_set.json", "prototype/data/robustness_and_fairness.json",
    "prototype/evals/results.md", "WRITEUP.md",
]

TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Customer Reply Prototype</title>
<link rel="stylesheet" href="__STLITE__/stlite.css" />
<style>
  body { margin: 0; background: #ffffff; font-family: system-ui, sans-serif; }
  #loading { padding: 24px 16px; color: #444; }
</style>
</head>
<body>
<div id="loading">Loading the prototype. The first visit takes about 15 to 30 seconds while the Python runtime starts in your browser.</div>
<div id="root"></div>
<!-- Generated by prototype/build_static.py from the prototype source files. Do not edit by hand. -->
<script id="app-files" type="application/json">__FILES__</script>
<script type="module">
  import { mount } from "__STLITE__/stlite.js";
  const files = JSON.parse(document.getElementById("app-files").textContent);
  mount({
    requirements: [],
    entrypoint: "prototype/app.py",
    files,
    streamlitConfig: { "client.toolbarMode": "viewer" },
  }, document.getElementById("root"));
  // stlite renders into #root; hide the loading note once the app has drawn something.
  new MutationObserver((_, obs) => {
    if (document.querySelector("#root [data-testid='stApp']")) { document.getElementById("loading").remove(); obs.disconnect(); }
  }).observe(document.getElementById("root"), { childList: true, subtree: true });
</script>
</body>
</html>
"""


def main():
    files = {f: (REPO / f).read_text(encoding="utf-8") for f in FILES}
    # "</" inside the JSON would end the <script> tag early; escape it.
    payload = json.dumps(files).replace("</", "<\\/")
    html = TEMPLATE.replace("__STLITE__", STLITE).replace("__FILES__", payload)
    out = REPO / "docs/index.html"
    out.parent.mkdir(exist_ok=True)
    out.write_text(html, encoding="utf-8")
    print(f"Wrote {out.relative_to(REPO)} ({len(html) // 1024} KB)")


if __name__ == "__main__":
    main()
